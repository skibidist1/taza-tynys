let lang = 'ru';
try { lang = localStorage.getItem('taza.lang') || (navigator.language?.startsWith('kk') ? 'kk' : 'ru'); } catch { /* ignore */ }

export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('taza.lang', l); } catch { /* ignore */ }
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function num(v, digits = 0) {
  if (v === null || v === undefined || Number.isNaN(v)) return '—';
  return Number(v).toLocaleString('ru-RU', { maximumFractionDigits: digits, minimumFractionDigits: 0 });
}

const WD = {
  ru: ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'],
  kk: ['жс', 'дс', 'сс', 'ср', 'бс', 'жм', 'сн'],
};
const MON = {
  ru: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
  kk: ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'],
};

export function weekday(day) {
  const [y, m, d] = day.split('-').map(Number);
  return WD[lang][new Date(Date.UTC(y, m - 1, d)).getUTCDay()];
}

export function dateLong(day) {
  const [, m, d] = day.split('-').map(Number);
  return lang === 'kk' ? `${d} ${MON.kk[m - 1]}` : `${d} ${MON.ru[m - 1]}`;
}

export const hhmm = (time) => time.slice(11, 16);
