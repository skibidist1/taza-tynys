export function weekday(day) {
  const [y, m, d] = day.split('-').map(Number);
  return WD[lang][new Date(Date.UTC(y, m - 1, d)).getUTCDay()];
}

export function dateLong(day, l = lang) {
  const [, m, d] = day.split('-').map(Number);
  return l === 'kk' ? `${d} ${MON.kk[m - 1]}` : `${d} ${MON.ru[m - 1]}`;
}

