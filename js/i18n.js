let lang = 'ru';
try { lang = localStorage.getItem('taza.lang') || (navigator.language?.startsWith('kk') ? 'kk' : 'ru'); } catch { /* ignore */ }

export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('taza.lang', l); } catch { /* ignore */ }
}

export function tl(l, key, vars = {}) {
  const s = DICT[l][key] ?? DICT.ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function num(v, digits = 0) {
  if (v === null || v === undefined || Number.isNaN(v)) return '—';
  return Number(v).toLocaleString('ru-RU', { maximumFractionDigits: digits, minimumFractionDigits: 0 });
}

